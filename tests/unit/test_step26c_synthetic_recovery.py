"""Step 26c synthetic parameter recovery through the 26a fitting library (S159, DRAFT_PENDING_26_0_H4).

Data are generated by sim_aa_1 from synthetic truths drawn inside these tests, then fitted with
culinarystate.simulation.kinetics.fitting and judged by identifiability.assess_identifiability. Coverage bands,
noise levels, scan widths and design grids are test settings, not the PROPOSED_PILOT G26-VER numbers (>= 200
datasets, coverage in [0.85, 0.95]), which only the signed 26.0 pre-registration can set. Never real data.
"""
from __future__ import annotations

import numpy as np
import pytest

from culinarystate.simulation import systems as S, verification as V
from culinarystate.simulation.kinetics import fitting as FT, identifiability as ID, models as M
from tests.fixtures import step26b_fixtures as F

TEMPS = (350.0, 356.0, 362.0, 368.0)
TAUS = (300.0, 900.0, 1500.0, 2100.0, 2700.0)


def tissue_only_data(truth: dict[str, float], rng: np.random.Generator, sigma: float):
    """ln-retention of A_t from sim_aa_1 runs without water contact (one run per temperature)."""
    params = F.aa_params(k_ref=truth["k_ref"], ea=truth["Ea"], k_l=None, k_p=None)
    tau, T, y = [], [], []
    for temp in TEMPS:
        cond = F.aa_conditions(contact="NO_WATER_CONTACT", sched=F.schedule((0.0, 2700.0, temp)), duration=2700.0)
        out = S.simulate(F.AA, cond, params, appdec=F.appdec(), solver=F.solver(times=(0.0, *TAUS)),
                         ms_limits=F.limits(), form_id=F.FORM_ID)
        assert out.status == "COMPLETED", out.reasons
        tau += list(TAUS)
        T += [temp] * len(TAUS)
        y += list(out.outputs["ln_retention_tissue"][1:])
    y = np.array(y) + rng.normal(0.0, sigma, len(y))
    return FT.Observations(y, {"tau_s": np.array(tau), "T_K": np.array(T)}, np.full(len(y), sigma),
                           "LN_RETENTION", "SYNTHETIC")


def criteria(widths: dict[str, float]) -> ID.IdentifiabilityCriteria:
    return ID.IdentifiabilityCriteria(profile_level=0.95, profile_half_width=widths, n_profile_points=6,
                                      rank_rtol=1e-8, max_condition_number=None, min_observations_per_parameter=None)


def test_first_order_arrhenius_recovery_from_simulator_data() -> None:
    rng = np.random.default_rng(159)
    truth = {"k_ref": float(np.exp(rng.uniform(-9.5, -8.0))), "Ea": float(rng.uniform(5e4, 9e4))}
    obs = tissue_only_data(truth, rng, sigma=0.01)
    form = M.FORMS["FIRST_ORDER_ARRHENIUS"]
    fit = FT.fit_least_squares(form, obs, starts=[{"k_ref": 1e-4, "Ea": 4e4}, {"k_ref": 5e-4, "Ea": 1e5}],
                               fixed={"T_ref_K": F.T_REF}, backend="numpy")
    assert fit.converged and fit.origin == "SYNTHETIC"
    rep = ID.assess_identifiability(form, obs, fit, criteria({"k_ref": 1.0, "Ea": 4e4}), backend="numpy")
    assert rep.overall_verdict == "IDENTIFIABLE"
    for p in rep.parameters:
        assert p.ci_low <= truth[p.parameter] <= p.ci_high
    with pytest.raises(FT.FitError):
        fit.as_param_provenance()                      # a synthetic fit never becomes PARAM provenance


def test_interval_coverage_over_repeated_synthetic_datasets() -> None:
    rng = np.random.default_rng(2026)
    truth = {"k_ref": 1.5e-4, "Ea": 7e4}
    form = M.FORMS["FIRST_ORDER_ARRHENIUS"]
    hits = {"k_ref": 0, "Ea": 0}
    n = 24
    for _ in range(n):
        obs = tissue_only_data(truth, rng, sigma=0.02)
        fit = FT.fit_least_squares(form, obs, starts=[{"k_ref": 1e-4, "Ea": 5e4}], fixed={"T_ref_K": F.T_REF},
                                   backend="numpy")
        rep = ID.assess_identifiability(form, obs, fit, criteria({"k_ref": 1.0, "Ea": 6e4}), backend="numpy")
        for p in rep.parameters:
            hits[p.parameter] += int(p.ci_low is not None and p.ci_low <= truth[p.parameter] <= p.ci_high)
    # Loose binomial band for a nominal 95 % interval over 24 datasets (test setting only).
    assert all(h / n >= 0.75 for h in hits.values()), hits


def leaching_form(free: tuple[str, ...], fixed_theta: dict[str, float], ratio: float):
    return V.simulator_kinetic_form(F.AA, free=free, fixed_theta=fixed_theta,
                                    system_inputs={"medium_contact": "WATER_IMMERSION",
                                                   "water_ratio_m3_per_kg": ratio, "k_dw_mode": "OFF"},
                                    name="SYNTH_SIM_AA_1_FIT")


def design(temps: tuple[float, ...], taus: tuple[float, ...], responses: tuple[int, ...]):
    tau, T, r = [], [], []
    for temp in temps:
        for t in taus:
            for i in responses:
                tau.append(t)
                T.append(temp)
                r.append(float(i))
    return {"tau_s": np.array(tau), "T_K": np.array(T), "response_index": np.array(r)}


def test_simulator_form_matches_the_simulator() -> None:
    truth = {"k_ref": 2e-4, "Ea": 7e4, "k_L": 3e-4}
    form = leaching_form(("k_ref", "Ea", "k_L"), {"K_p": 2e-3}, 4e-3)
    cov = design((F.T_BATH,), (600.0, 1200.0, 1800.0), (0, 1))
    y = form.predict(truth, cov, {"T_ref_K": F.T_REF})
    out = S.simulate(F.AA, F.aa_conditions(), F.aa_params(), appdec=F.appdec(), solver=F.solver(),
                     ms_limits=F.limits(), form_id=F.FORM_ID)
    want = np.ravel(np.column_stack([np.log(out.states["A_t"][1:]), np.log(out.states["A_w"][1:])]))
    assert np.allclose(y, want, rtol=1e-12)
    with pytest.raises(ValueError):
        leaching_form(("k_ref", "T_ref"), {"Ea": 7e4, "k_L": 3e-4, "K_p": 2e-3}, 4e-3)   # T_ref is a fixed input


def test_leaching_recovery_with_a_water_assay_design() -> None:
    rng = np.random.default_rng(7)
    truth = {"k_ref": float(np.exp(rng.uniform(-9.0, -8.0))), "Ea": float(rng.uniform(5e4, 9e4)),
             "k_L": float(np.exp(rng.uniform(-9.0, -7.5)))}
    form = leaching_form(("k_ref", "Ea", "k_L"), {"K_p": 2e-3}, 4e-3)
    cov = design(TEMPS, TAUS, (0, 1))
    sigma = 0.01
    y = form.predict(truth, cov, {"T_ref_K": F.T_REF}) + rng.normal(0.0, sigma, cov["tau_s"].size)
    obs = FT.Observations(y, cov, np.full(y.size, sigma), "LN_RETENTION", "SYNTHETIC")
    fit = FT.fit_least_squares(form, obs, starts=[{"k_ref": 1e-4, "Ea": 6e4, "k_L": 1e-4}],
                               fixed={"T_ref_K": F.T_REF}, backend="numpy")
    rep = ID.assess_identifiability(form, obs, fit, criteria({"k_ref": 1.0, "Ea": 4e4, "k_L": 1.0}),
                                    backend="numpy")
    assert rep.overall_verdict == "IDENTIFIABLE", [(p.parameter, p.reasons) for p in rep.parameters]
    for p in rep.parameters:
        assert p.ci_low <= truth[p.parameter] <= p.ci_high


def test_no_water_assay_single_temperature_design_flags_k_l_not_identifiable() -> None:
    # Negative control (card E26-1 / G26-VER): tissue-only data at one temperature with a weak back-exchange
    # (K_p / r small) cannot separate degradation from leaching; k_L must not be reported.
    rng = np.random.default_rng(11)
    truth = {"k_ref": 2e-4, "k_L": 3e-4}
    form = leaching_form(("k_ref", "k_L"), {"Ea": 7e4, "K_p": 4e-6}, 4e-3)
    cov = design((F.T_BATH,), TAUS, (0,))
    sigma = 0.01
    y = form.predict(truth, cov, {"T_ref_K": F.T_REF}) + rng.normal(0.0, sigma, cov["tau_s"].size)
    obs = FT.Observations(y, cov, np.full(y.size, sigma), "LN_RETENTION", "SYNTHETIC")
    fit = FT.fit_least_squares(form, obs, starts=[{"k_ref": 1e-4, "k_L": 1e-4}], fixed={"T_ref_K": F.T_REF},
                               backend="numpy")
    rep = ID.assess_identifiability(form, obs, fit, criteria({"k_ref": 3.0, "k_L": 3.0}), backend="numpy")
    kl = next(p for p in rep.parameters if p.parameter == "k_L")
    assert kl.verdict == "NOT_IDENTIFIABLE" and kl.ci_low is None and kl.ci_high is None
    assert "k_L" not in rep.reportable_estimates()


def test_shuffled_temperature_negative_control_does_not_recover_ea() -> None:
    rng = np.random.default_rng(3)
    truth = {"k_ref": 1.5e-4, "Ea": 7e4}
    obs = tissue_only_data(truth, rng, sigma=0.01)
    shuffled = FT.Observations(obs.response, {"tau_s": obs.covariates["tau_s"],
                                              "T_K": rng.permutation(obs.covariates["T_K"])},
                               obs.sigma, "LN_RETENTION", "SYNTHETIC")
    form = M.FORMS["FIRST_ORDER_ARRHENIUS"]
    fit = FT.fit_least_squares(form, shuffled, starts=[{"k_ref": 1e-4, "Ea": 5e4}], fixed={"T_ref_K": F.T_REF},
                               backend="numpy")
    rep = ID.assess_identifiability(form, shuffled, fit, criteria({"k_ref": 1.0, "Ea": 6e4}), backend="numpy")
    ea = next(p for p in rep.parameters if p.parameter == "Ea")
    recovered = ea.verdict == "IDENTIFIABLE" and ea.ci_low <= truth["Ea"] <= ea.ci_high
    assert not recovered
